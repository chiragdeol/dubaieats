import type { Restaurant } from "./restaurants";

function mapThumb(lat: number, lng: number) {
  return `https://staticmap.openstreetmap.de/staticmap.php?center=${lat},${lng}&zoom=16&size=800x500&maptype=mapnik`;
}

function reviewsLabel(count: number) {
  return count >= 1000 ? `${(count / 1000).toFixed(count >= 10000 ? 0 : 1)}K` : String(count);
}

function venue(
  row: Omit<Restaurant, "image" | "reviews" | "status"> & Partial<Pick<Restaurant, "image" | "status">>
): Restaurant {
  return {
    ...row,
    status: row.status || "Open",
    reviews: reviewsLabel(row.reviewsCount),
    image: row.image || mapThumb(row.latitude, row.longitude),
  };
}

